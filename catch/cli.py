import argparse
import sys
import shutil
import re
from pathlib import Path

from catch.config import parse_config, ConfigError
from catch.generator import generate_cmakelists
from catch.runner import run_command, RunnerError
from catch.lock import update_lock_for_project, resolve_git_commit, save_lock, load_lock
from catch.docs import cmd_docs
from catch.doctor import cmd_doctor
from catch import templates

def is_tool_available(name: str) -> bool:
    return shutil.which(name) is not None

def infer_dep_name_from_url(url: str) -> str:
    cleaned = url.rstrip('/')
    if cleaned.endswith('.git'):
        cleaned = cleaned[:-4]
    name = cleaned.split('/')[-1]
    return name or "dep"

def cmd_new(args):
    name = args.name
    project_dir = Path.cwd() / name

    if project_dir.exists() and any(project_dir.iterdir()):
        print(f"Directory '{name}' exists and is not empty.")
        if not args.force:
            resp = input("Overwrite files in this directory? [y/N]: ").strip().lower()
            if resp != 'y':
                print("Aborted.")
                sys.exit(1)

    project_dir.mkdir(parents=True, exist_ok=True)
    src_dir = project_dir / "src"
    src_dir.mkdir(exist_ok=True)

    langs = ["CXX"]
    if args.cuda:
        langs.append("CUDA")

    cuda_sec = ""
    if args.cuda:
        cuda_sec = "\n[cuda]\narch = [\"native\"]\nstd = \"17\"\nflags = []\n"

    llvm_sec = ""
    if args.mlir:
        llvm_sec = "\n[llvm]\ndir = \"/path/to/llvm-build/lib/cmake/llvm\"\nmlir_dir = \"/path/to/llvm-build/lib/cmake/mlir\"\nmlir = true\ncomponents = [\"Support\", \"Core\"]\nmlir_libs = [\"MLIRIR\", \"MLIRParser\", \"MLIRSupport\"]\n"

    langs_str = str(langs).replace("'", '"')
    catch_toml = templates.CATCH_TOML_TEMPLATE.format(
        name=name,
        languages=langs_str,
        cuda_section=cuda_sec,
        llvm_section=llvm_sec
    )

    (project_dir / "catch.toml").write_text(catch_toml, encoding="utf-8")
    (project_dir / ".gitignore").write_text(templates.GITIGNORE_TEMPLATE, encoding="utf-8")

    if args.mlir:
        (src_dir / "main.cpp").write_text(templates.MLIR_MAIN_CPP_TEMPLATE, encoding="utf-8")
    else:
        (src_dir / "main.cpp").write_text(templates.MAIN_CPP_TEMPLATE, encoding="utf-8")

    if args.cuda:
        (src_dir / "kernel.cu").write_text(templates.KERNEL_CU_TEMPLATE, encoding="utf-8")

    print(f"Created catch project '{name}'.")


def ensure_cmakelists(project_dir: Path, verbose: bool = False):
    config_path = project_dir / "catch.toml"
    if not config_path.exists():
        print(f"Error: catch.toml not found in {project_dir}", file=sys.stderr)
        sys.exit(1)

    cfg = parse_config(config_path)

    # Ensure dependencies in lock file
    lock_data = update_lock_for_project(project_dir, force_update_dep=False)

    cmake_content = generate_cmakelists(cfg, project_dir, lock_data=lock_data)
    cmakelists_path = project_dir / "CMakeLists.txt"

    # Check if CMakeLists.txt was created by catch
    if cmakelists_path.exists():
        existing = cmakelists_path.read_text(encoding="utf-8")
        if not existing.startswith("# Generated by catch. Do not edit."):
            print("Error: Existing CMakeLists.txt was not generated by catch. Refusing to overwrite user file.", file=sys.stderr)
            sys.exit(1)

    cmakelists_path.write_text(cmake_content, encoding="utf-8")
    if verbose:
        print("Generated CMakeLists.txt successfully.")
    return cfg


def cmd_build(args):
    project_dir = Path.cwd()
    cfg = ensure_cmakelists(project_dir, verbose=getattr(args, 'verbose', False))

    if not is_tool_available("cmake"):
        print("Error: 'cmake' executable not found in PATH.", file=sys.stderr)
        sys.exit(1)

    generator = []
    if is_tool_available("ninja"):
        generator = ["-G", "Ninja"]

    release = getattr(args, 'release', False)
    verbose = getattr(args, 'verbose', False)
    build_type = "Release" if release else "Debug"
    configure_cmd = ["cmake", "-S", ".", "-B", "build"] + generator + [f"-DCMAKE_BUILD_TYPE={build_type}"]

    if cfg.llvm:
        if cfg.llvm.dir:
            configure_cmd.append(f"-DLLVM_DIR={cfg.llvm.dir}")
        if cfg.llvm.mlir_dir:
            configure_cmd.append(f"-DMLIR_DIR={cfg.llvm.mlir_dir}")

    try:
        run_command(configure_cmd, cwd=project_dir, verbose=verbose)
        build_cmd = ["cmake", "--build", "build", "--config", build_type]
        run_command(build_cmd, cwd=project_dir, verbose=verbose)
    except RunnerError as e:
        if cfg.llvm:
            print("Set [llvm].dir and mlir_dir to the cmake folders inside your LLVM build, not a system LLVM package without MLIR.", file=sys.stderr)
        sys.exit(1)


def cmd_run(args):
    cmd_build(args)

    project_dir = Path.cwd()
    cfg = parse_config(project_dir / "catch.toml")

    if cfg.package.type != "bin":
        print("Error: 'catch run' can only be executed on binary packages (type = 'bin').", file=sys.stderr)
        sys.exit(1)

    exe_path = project_dir / "build" / cfg.package.name
    if sys.platform == "win32":
        exe_path = project_dir / "build" / f"{cfg.package.name}.exe"
        if not exe_path.exists():
            release = getattr(args, 'release', False)
            exe_path = project_dir / "build" / ("Release" if release else "Debug") / f"{cfg.package.name}.exe"

    if not exe_path.exists():
        print(f"Error: Executable not found at {exe_path}", file=sys.stderr)
        sys.exit(1)

    run_args = [str(exe_path)]
    if hasattr(args, 'args') and args.args:
        run_args.extend(args.args)

    try:
        run_command(run_args, cwd=project_dir, verbose=getattr(args, 'verbose', False))
    except RunnerError:
        sys.exit(1)


def cmd_test(args):
    cmd_build(args)

    project_dir = Path.cwd()
    if not is_tool_available("ctest"):
        print("Error: 'ctest' executable not found in PATH.", file=sys.stderr)
        sys.exit(1)

    ctest_cmd = ["ctest", "--test-dir", "build", "--output-on-failure"]
    try:
        run_command(ctest_cmd, cwd=project_dir, verbose=getattr(args, 'verbose', False))
    except RunnerError:
        sys.exit(1)


def cmd_clean(args):
    build_dir = Path.cwd() / "build"
    if build_dir.exists():
        print(f"Removing {build_dir}")
        shutil.rmtree(build_dir)
    else:
        print("build/ directory does not exist.")


def cmd_add(args):
    project_dir = Path.cwd()
    toml_path = project_dir / "catch.toml"
    if not toml_path.exists():
        print("Error: catch.toml not found.", file=sys.stderr)
        sys.exit(1)

    name = args.name or infer_dep_name_from_url(args.url)

    # First remove existing entry if present to avoid duplicated keys
    content = toml_path.read_text(encoding="utf-8")
    lines = content.splitlines(keepends=True)
    filtered_lines = []
    for line in lines:
        if line.strip().startswith(f"{name} =") or line.strip().startswith(f'"{name}" ='):
            continue
        filtered_lines.append(line)
    content = "".join(filtered_lines)

    ref_part = ""
    if args.tag:
        ref_part += f', tag = "{args.tag}"'
    elif args.branch:
        ref_part += f', branch = "{args.branch}"'
    elif args.rev:
        ref_part += f', rev = "{args.rev}"'

    target_part = f', target = "{args.target}"' if args.target else ""

    dep_line = f'{name} = {{ git = "{args.url}"{ref_part}{target_part} }}\n'

    if "[dependencies]" in content:
        lines = content.splitlines(keepends=True)
        new_lines = []
        in_deps = False
        appended = False
        for line in lines:
            new_lines.append(line)
            if line.strip() == "[dependencies]":
                in_deps = True
            elif in_deps and line.strip().startswith("["):
                new_lines.insert(-1, dep_line)
                appended = True
                in_deps = False
        if in_deps and not appended:
            new_lines.append(dep_line)
        content = "".join(new_lines)
    else:
        content += f"\n[dependencies]\n{dep_line}"

    toml_path.write_text(content, encoding="utf-8")
    print(f"Added dependency '{name}' to catch.toml")

    # Update lock file
    update_lock_for_project(project_dir, force_update_dep=name)


def cmd_remove(args):
    project_dir = Path.cwd()
    toml_path = project_dir / "catch.toml"
    if not toml_path.exists():
        print("Error: catch.toml not found.", file=sys.stderr)
        sys.exit(1)

    content = toml_path.read_text(encoding="utf-8")
    lines = content.splitlines(keepends=True)
    new_lines = []
    removed = False

    for line in lines:
        if line.strip().startswith(f"{args.name} =") or line.strip().startswith(f'"{args.name}" ='):
            removed = True
            continue
        new_lines.append(line)

    if not removed:
        print(f"Dependency '{args.name}' not found in catch.toml.", file=sys.stderr)
        sys.exit(1)

    toml_path.write_text("".join(new_lines), encoding="utf-8")
    print(f"Removed dependency '{args.name}' from catch.toml")

    # Remove from lock file
    lock_path = project_dir / "catch.lock"
    if lock_path.exists():
        lock_data = load_lock(lock_path)
        deps = lock_data.get("dependencies", {})
        if args.name in deps:
            del deps[args.name]
            save_lock(lock_path, lock_data)


def cmd_update(args):
    project_dir = Path.cwd()
    dep_name = args.name if hasattr(args, 'name') else None
    update_lock_for_project(project_dir, force_update_dep=dep_name or None)
    print("Updated catch.lock")


def main():
    parser = argparse.ArgumentParser(prog="catch", description="A Cargo-like tool for C++")
    parser.add_argument("--verbose", "-v", action="store_true", help="Enable verbose output")
    subparsers = parser.add_subparsers(dest="command", help="Sub-commands")

    # new
    parser_new = subparsers.add_parser("new", help="Create a new catch C++ project")
    parser_new.add_argument("name", help="Project name")
    parser_new.add_argument("--cuda", action="store_true", help="Enable CUDA support")
    parser_new.add_argument("--mlir", action="store_true", help="Enable MLIR/LLVM support")
    parser_new.add_argument("--force", "-f", action="store_true", help="Force overwrite without prompt")

    # build
    parser_build = subparsers.add_parser("build", help="Build the project")
    parser_build.add_argument("--release", action="store_true", help="Build in Release mode")

    # run
    parser_run = subparsers.add_parser("run", help="Build and run the main executable")
    parser_run.add_argument("--release", action="store_true", help="Build in Release mode")
    parser_run.add_argument("args", nargs=argparse.REMAINDER, help="Arguments passed to executable after '--'")

    # test
    parser_test = subparsers.add_parser("test", help="Run tests with ctest")
    parser_test.add_argument("--release", action="store_true", help="Build in Release mode before testing")

    # clean
    parser_clean = subparsers.add_parser("clean", help="Remove the build directory")

    # add
    parser_add = subparsers.add_parser("add", help="Add a git dependency")
    parser_add.add_argument("url", help="Git repository URL")
    parser_add.add_argument("--tag", "-t", help="Git tag")
    parser_add.add_argument("--branch", "-b", help="Git branch")
    parser_add.add_argument("--rev", "-r", help="Git revision / commit hash")
    parser_add.add_argument("--name", "-n", help="Dependency name override")
    parser_add.add_argument("--target", help="CMake target override (e.g. fmt::fmt)")

    # remove
    parser_remove = subparsers.add_parser("remove", help="Remove a dependency")
    parser_remove.add_argument("name", help="Dependency name")

    # update
    parser_update = subparsers.add_parser("update", help="Update dependency lock file")
    parser_update.add_argument("name", nargs="?", help="Specific dependency name to update")

    # docs
    parser_docs = subparsers.add_parser("docs", help="Generate project documentation")
    parser_docs.add_argument("--stdout", action="store_true", help="Print documentation to stdout instead of file")

    # doctor
    parser_doctor = subparsers.add_parser("doctor", help="Check system toolchain dependencies")

    args = parser.parse_args()

    # Filter out '--' from args if present in run
    if hasattr(args, "args") and args.args and args.args[0] == "--":
        args.args = args.args[1:]

    try:
        if args.command == "new":
            cmd_new(args)
        elif args.command == "build":
            cmd_build(args)
        elif args.command == "run":
            cmd_run(args)
        elif args.command == "test":
            cmd_test(args)
        elif args.command == "clean":
            cmd_clean(args)
        elif args.command == "add":
            cmd_add(args)
        elif args.command == "remove":
            cmd_remove(args)
        elif args.command == "update":
            cmd_update(args)
        elif args.command == "docs":
            cmd_docs(args)
        elif args.command == "doctor":
            cmd_doctor(args)
        else:
            parser.print_help()
    except ConfigError as e:
        print(f"Configuration Error: {e}", file=sys.stderr)
        sys.exit(1)
    except Exception as e:
        print(f"Error: {e}", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
