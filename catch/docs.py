import sys
from pathlib import Path
from catch.config import parse_config, ConfigError
from catch.lock import load_lock

GENERATED_NOTE = "<!-- Generated by catch docs. Do not edit directly. -->\n"

def generate_docs(project_dir: Path) -> str:
    config_path = project_dir / "catch.toml"
    if not config_path.exists():
        raise ConfigError(f"catch.toml not found in {project_dir}")

    cfg = parse_config(config_path)
    lock_data = load_lock(project_dir / "catch.lock")
    lock_deps = lock_data.get("dependencies", {})

    lines = [
        GENERATED_NOTE,
        f"# Project: {cfg.package.name}",
        "",
        f"- **Version**: `{cfg.package.version}`",
        f"- **Type**: `{cfg.package.type}`",
        "",
        "## Languages and Standard",
        f"- **Languages**: {', '.join(cfg.build.languages)}",
        f"- **C++ Standard**: `{cfg.build.std}`",
        f"- **Compile Flags**: `{cfg.build.flags}`",
        f"- **Defines**: `{cfg.build.defines}`",
        f"- **Release Flags**: `{cfg.build.release_flags}`",
        "",
        "## Source Tree",
    ]

    # Discover files
    src_files = sorted([f.relative_to(project_dir).as_posix() for f in (project_dir / "src").rglob("*") if f.is_file()]) if (project_dir / "src").exists() else []
    inc_files = sorted([f.relative_to(project_dir).as_posix() for f in (project_dir / "include").rglob("*") if f.is_file()]) if (project_dir / "include").exists() else []
    test_files = sorted([f.relative_to(project_dir).as_posix() for f in (project_dir / "tests").rglob("*") if f.is_file()]) if (project_dir / "tests").exists() else []

    if src_files:
        lines.append("### Source Files (`src/`)")
        for f in src_files:
            lines.append(f"- `{f}`")
    if inc_files:
        lines.append("### Header Files (`include/`)")
        for f in inc_files:
            lines.append(f"- `{f}`")
    if test_files:
        lines.append("### Test Files (`tests/`)")
        for f in test_files:
            lines.append(f"- `{f}`")

    lines.append("")
    lines.append("## Targets")
    lines.append(f"- **Main Target**: `{cfg.package.name}` ({cfg.package.type})")
    if test_files:
        lines.append("- **Test Executables**:")
        for tf in test_files:
            lines.append(f"  - `test_{Path(tf).stem}` (from `{tf}`)")

    lines.append("")
    lines.append("## Dependencies")
    if cfg.dependencies:
        for name, dep in sorted(cfg.dependencies.items()):
            locked = lock_deps.get(name, {})
            ref = dep.tag or dep.branch or dep.rev or "HEAD"
            commit = locked.get("commit", "unlocked")
            target = dep.target or f"{name}::{name}"
            lines.append(f"- **{name}**")
            lines.append(f"  - URL: `{dep.git}`")
            lines.append(f"  - Requested Ref: `{ref}`")
            lines.append(f"  - Locked Commit: `{commit}`")
            lines.append(f"  - Target: `{target}`")
    else:
        lines.append("No dependencies declared.")

    if cfg.cuda:
        lines.append("")
        lines.append("## CUDA Settings")
        lines.append(f"- **Architectures**: `{cfg.cuda.arch}`")
        lines.append(f"- **CUDA Standard**: `{cfg.cuda.std}`")
        lines.append(f"- **Flags**: `{cfg.cuda.flags}`")
        lines.append(f"- **Separable Compilation**: `{cfg.cuda.separable}`")

    if cfg.llvm:
        lines.append("")
        lines.append("## LLVM & MLIR Settings")
        lines.append(f"- **LLVM Dir**: `{cfg.llvm.dir}`")
        lines.append(f"- **MLIR Enabled**: `{cfg.llvm.mlir}`")
        if cfg.llvm.mlir_dir:
            lines.append(f"- **MLIR Dir**: `{cfg.llvm.mlir_dir}`")
        lines.append(f"- **Components**: `{cfg.llvm.components}`")
        if cfg.llvm.mlir_libs:
            lines.append(f"- **MLIR Libraries**: `{cfg.llvm.mlir_libs}`")

    lines.append("")
    lines.append("## Build Commands")
    lines.append("Commands run by `catch` for this project:")
    lines.append("```sh")
    lines.append("cmake -S . -B build -G Ninja -DCMAKE_BUILD_TYPE=Debug")
    lines.append("cmake --build build")
    lines.append("ctest --test-dir build --output-on-failure")
    lines.append("```")

    lines.append("")
    lines.append("## Catch Commands Help")
    lines.append("- `catch new <name> [--cuda] [--mlir]`: Creates a new C++ project.")
    lines.append("- `catch build [--release]`: Regenerates CMakeLists.txt and compiles the project.")
    lines.append("- `catch run [-- args]`: Builds and executes the main project binary.")
    lines.append("- `catch test`: Builds and runs all tests using CTest.")
    lines.append("- `catch clean`: Deletes the build/ directory.")
    lines.append("- `catch add <url> [--tag|--branch|--rev] [--name] [--target]`: Adds a git dependency.")
    lines.append("- `catch remove <name>`: Removes a dependency from catch.toml.")
    lines.append("- `catch update [name]`: Re-resolves git dependency commit hashes in catch.lock.")
    lines.append("- `catch docs [--stdout]`: Generates docs/PROJECT.md documentation.")
    lines.append("- `catch doctor`: Checks for required toolchain dependencies and system setup.")

    return "\n".join(lines) + "\n"


def cmd_docs(args):
    project_dir = Path.cwd()
    content = generate_docs(project_dir)

    if getattr(args, "stdout", False):
        sys.stdout.write(content)
    else:
        docs_dir = project_dir / "docs"
        docs_dir.mkdir(exist_ok=True)
        doc_file = docs_dir / "PROJECT.md"
        doc_file.write_text(content, encoding="utf-8")
        print(f"Wrote documentation to {doc_file.relative_to(project_dir)}")
