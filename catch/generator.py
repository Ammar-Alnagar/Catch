from pathlib import Path
from typing import List
from catch.config import CatchConfig

HEADER_COMMENT = "# Generated by catch. Do not edit.\n"

def sort_files(files: List[Path]) -> List[Path]:
    return sorted([f.as_posix() for f in files])

def generate_cmakelists(config: CatchConfig, project_dir: Path, lock_data: dict = None) -> str:
    lines = [
        HEADER_COMMENT,
        "cmake_minimum_required(VERSION 3.24)",
    ]

    langs = " ".join(config.build.languages)
    lines.append(f"project({config.package.name} LANGUAGES {langs})")
    lines.append("")

    lines.append("set(CMAKE_EXPORT_COMPILE_COMMANDS ON)")
    if "CXX" in config.build.languages:
        lines.append(f"set(CMAKE_CXX_STANDARD {config.build.std})")
        lines.append("set(CMAKE_CXX_STANDARD_REQUIRED ON)")

    # Build flags
    if config.build.flags:
        flags_str = " ".join(config.build.flags)
        lines.append(f"add_compile_options({flags_str})")

    if config.build.defines:
        for d in config.build.defines:
            lines.append(f"add_compile_definitions({d})")

    # Release flags
    if config.build.release_flags:
        rel_flags_str = " ".join(config.build.release_flags)
        lines.append(f"string(APPEND CMAKE_CXX_FLAGS_RELEASE \" {rel_flags_str}\")")

    lines.append("")

    # CUDA settings
    if "CUDA" in config.build.languages and config.cuda:
        lines.append("enable_language(CUDA)")
        lines.append(f"set(CMAKE_CUDA_STANDARD {config.cuda.std})")
        lines.append("set(CMAKE_CUDA_STANDARD_REQUIRED ON)")
        if config.cuda.arch:
            arch_str = ";".join(config.cuda.arch)
            lines.append(f'if(NOT DEFINED CMAKE_CUDA_ARCHITECTURES)\n  set(CMAKE_CUDA_ARCHITECTURES "{arch_str}")\nendif()')
        if config.cuda.flags:
            cflags = " ".join(config.cuda.flags)
            lines.append(f"add_compile_options($<$<COMPILE_LANGUAGE:CUDA>:{cflags}>)")
        if config.cuda.separable:
            lines.append("set(CMAKE_CUDA_SEPARABLE_COMPILATION ON)")
        lines.append("")

    # LLVM & MLIR settings
    if config.llvm:
        lines.append("# LLVM & MLIR configuration")
        lines.append("find_package(LLVM REQUIRED CONFIG)")
        lines.append('message(STATUS "Using LLVMConfig.cmake in ${LLVM_DIR}")')
        if config.llvm.mlir:
            lines.append("find_package(MLIR REQUIRED CONFIG)")
            lines.append('message(STATUS "Using MLIRConfig.cmake in ${MLIR_DIR}")')

        lines.append('list(APPEND CMAKE_MODULE_PATH "${LLVM_CMAKE_DIR}")')
        if config.llvm.mlir:
            lines.append('list(APPEND CMAKE_MODULE_PATH "${MLIR_CMAKE_DIR}")')

        lines.append("include(TableGen)")
        lines.append("include(AddLLVM)")
        if config.llvm.mlir:
            lines.append("include(AddMLIR)")
        lines.append("include(HandleLLVMOptions)")

        lines.append("include_directories(${LLVM_INCLUDE_DIRS})")
        if config.llvm.mlir:
            lines.append("include_directories(${MLIR_INCLUDE_DIRS})")

        lines.append("add_definitions(${LLVM_DEFINITIONS})")

        # RTTI check
        lines.append('if(NOT LLVM_ENABLE_RTTI)\n  if(MSVC)\n    add_compile_options(/GR-)\n  else()\n    add_compile_options(-fno-rtti)\n  endif()\nendif()')
        lines.append("")

    # FetchContent dependencies
    if config.dependencies:
        lines.append("include(FetchContent)")
        lock_deps = lock_data.get("dependencies", {}) if lock_data else {}

        for dep_name, dep in sorted(config.dependencies.items()):
            locked_commit = lock_deps.get(dep_name, {}).get("commit")
            tag_to_use = locked_commit or dep.tag or dep.branch or dep.rev or "HEAD"
            lines.append(f"FetchContent_Declare(\n  {dep_name}\n  GIT_REPOSITORY {dep.git}\n  GIT_TAG {tag_to_use}\n)")
            lines.append(f"FetchContent_MakeAvailable({dep_name})")

            # Target linking target determination
            target = dep.target
            if not target:
                target = f"{dep_name}::{dep_name}"

            # Fallback logic in CMake if target doesn't exist
            lines.append(f'if(TARGET {target})\n  set({dep_name}_LINK_TARGET "{target}")')
            lines.append(f'elif(TARGET {dep_name})\n  set({dep_name}_LINK_TARGET "{dep_name}")')
            lines.append(f'else()\n  message(WARNING "Target \'{target}\' or \'{dep_name}\' for dependency \'{dep_name}\' not found after configure.")')
            lines.append(f'  set({dep_name}_LINK_TARGET "{target}")\nendif()')
            lines.append("")

    # Sources discovery
    src_dir = project_dir / "src"
    sources = []
    if src_dir.exists():
        for ext in ("*.cpp", "*.cc", "*.c", "*.cu"):
            sources.extend(src_dir.rglob(ext))

    rel_sources = sorted([s.relative_to(project_dir).as_posix() for s in sources])

    inc_dir = project_dir / "include"
    has_include = inc_dir.exists() and inc_dir.is_dir()

    # Targets (bin or lib)
    if config.package.type == "bin":
        lines.append(f"add_executable({config.package.name})")
        if rel_sources:
            sources_str = "\n  ".join(rel_sources)
            lines.append(f"target_sources({config.package.name} PRIVATE\n  {sources_str}\n)")
    else: # lib
        # exclude main.cpp if present
        lib_sources = [s for s in rel_sources if not s.endswith("main.cpp")]
        lines.append(f"add_library({config.package.name})")
        if lib_sources:
            sources_str = "\n  ".join(lib_sources)
            lines.append(f"target_sources({config.package.name} PRIVATE\n  {sources_str}\n)")

    if has_include:
        lines.append(f"target_include_directories({config.package.name} PUBLIC include)")

    # Link dependencies
    if config.dependencies:
        for dep_name in sorted(config.dependencies.keys()):
            lines.append(f"target_link_libraries({config.package.name} PRIVATE ${{{dep_name}_LINK_TARGET}})")

    if "CUDA" in config.build.languages:
        lines.append(f"target_link_libraries({config.package.name} PRIVATE CUDA::cudart)")

    if config.llvm:
        if config.llvm.components:
            comp_str = " ".join(config.llvm.components)
            lines.append(f"llvm_map_components_to_libnames(llvm_libs {comp_str})")
            lines.append(f"target_link_libraries({config.package.name} PRIVATE ${{llvm_libs}})")
        if config.llvm.mlir and config.llvm.mlir_libs:
            mlir_lib_str = " ".join(config.llvm.mlir_libs)
            lines.append(f"target_link_libraries({config.package.name} PRIVATE {mlir_lib_str})")

    lines.append("")

    # Tests discovery
    tests_dir = project_dir / "tests"
    test_files = []
    if tests_dir.exists():
        for ext in ("*.cpp", "*.cc", "*.c", "*.cu"):
            test_files.extend(tests_dir.rglob(ext))

    if test_files:
        lines.append("enable_testing()")
        for tf in sorted(test_files):
            rel_tf = tf.relative_to(project_dir).as_posix()
            test_name = tf.stem
            target_name = f"test_{test_name}"
            lines.append(f"add_executable({target_name} {rel_tf})")
            if has_include:
                lines.append(f"target_include_directories({target_name} PRIVATE include)")
            if config.package.type == "lib":
                lines.append(f"target_link_libraries({target_name} PRIVATE {config.package.name})")
            if config.dependencies:
                for dep_name in sorted(config.dependencies.keys()):
                    lines.append(f"target_link_libraries({target_name} PRIVATE ${{{dep_name}_LINK_TARGET}})")
            lines.append(f"add_test(NAME {test_name} COMMAND {target_name})")
        lines.append("")

    # extra.cmake inclusion
    extra_cmake = project_dir / "extra.cmake"
    if extra_cmake.exists():
        lines.append("if(EXISTS \"${CMAKE_CURRENT_SOURCE_DIR}/extra.cmake\")")
        lines.append("  include(\"${CMAKE_CURRENT_SOURCE_DIR}/extra.cmake\")")
        lines.append("endif()")

    return "\n".join(lines) + "\n"
