import re
import sys
import tomllib
from pathlib import Path
from typing import Dict, Any, Optional
from catch.runner import run_command, RunnerError

def resolve_git_commit(url: str, ref: Optional[str] = None) -> str:
    """
    Resolves git commit hash using `git ls-remote <url> <ref>`.
    """
    cmd = ["git", "ls-remote", url]
    if ref:
        cmd.append(ref)

    try:
        res = run_command(cmd, capture_output=True, check=True)
        out = res.stdout.strip()
        if not out:
            # Try without ref if ref returned nothing, or fallback to HEAD
            res = run_command(["git", "ls-remote", url, "HEAD"], capture_output=True, check=True)
            out = res.stdout.strip()

        if not out:
            raise RunnerError(f"Could not resolve commit hash for {url} ref '{ref}'")

        # First line, first column
        first_line = out.splitlines()[0]
        commit_hash = first_line.split()[0]
        return commit_hash
    except Exception as e:
        raise RunnerError(f"Failed to resolve git dependency commit for {url} ({ref}): {e}") from e


def load_lock(lock_path: Path) -> dict:
    if not lock_path.exists():
        return {"dependencies": {}}
    try:
        content = lock_path.read_text(encoding="utf-8")
        return tomllib.loads(content)
    except Exception:
        return {"dependencies": {}}


def save_lock(lock_path: Path, lock_data: dict) -> None:
    lines = ["# Generated by catch. Do not edit.", ""]
    deps = lock_data.get("dependencies", {})
    for name in sorted(deps.keys()):
        info = deps[name]
        lines.append(f"[dependencies.{name}]")
        lines.append(f'url = "{info.get("url", "")}"')
        if info.get("ref"):
            lines.append(f'requested_ref = "{info.get("ref")}"')
        lines.append(f'commit = "{info.get("commit", "")}"')
        lines.append("")

    lock_path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def update_lock_for_project(project_dir: Path, force_update_dep: Optional[str] = None) -> dict:
    config_path = project_dir / "catch.toml"
    from catch.config import parse_config
    cfg = parse_config(config_path)

    lock_path = project_dir / "catch.lock"
    lock_data = load_lock(lock_path)
    locked_deps = lock_data.get("dependencies", {})

    updated = False
    new_deps = {}

    for name, dep in cfg.dependencies.items():
        ref = dep.tag or dep.branch or dep.rev or "HEAD"
        # Re-resolve if dep not locked or if force_update_dep matches
        if name not in locked_deps or force_update_dep in (None, name) or locked_deps[name].get("url") != dep.git or locked_deps[name].get("ref") != ref:
            print(f"Resolving dependency '{name}' ({dep.git} @ {ref})...")
            commit = resolve_git_commit(dep.git, ref if ref != "HEAD" else None)
            new_deps[name] = {
                "url": dep.git,
                "ref": ref,
                "commit": commit
            }
            updated = True
        else:
            new_deps[name] = locked_deps[name]

    lock_data = {"dependencies": new_deps}
    save_lock(lock_path, lock_data)
    return lock_data
