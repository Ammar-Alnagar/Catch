use anyhow::{anyhow, Result};
use std::path::{Path, PathBuf};
use walkdir::WalkDir;

use crate::config::parse_config;
use crate::lock::load_lock;

pub const GENERATED_NOTE: &str = "<!-- Generated by catch docs. Do not edit directly. -->\n";

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum SymbolKind {
    Function,
    Class,
    Struct,
    Enum,
    Namespace,
}

impl SymbolKind {
    pub fn as_str(&self) -> &'static str {
        match self {
            SymbolKind::Function => "Function",
            SymbolKind::Class => "Class",
            SymbolKind::Struct => "Struct",
            SymbolKind::Enum => "Enum",
            SymbolKind::Namespace => "Namespace",
        }
    }
}

#[derive(Debug, Clone)]
pub struct CodeSymbol {
    pub kind: SymbolKind,
    pub name: String,
    pub signature: String,
    pub line: usize,
    pub doc: Option<String>,
}

#[derive(Debug, Default, Clone)]
pub struct FileMetrics {
    pub path: String,
    pub total_lines: usize,
    pub code_lines: usize,
    pub comment_lines: usize,
    pub blank_lines: usize,
    pub size_bytes: u64,
    pub symbols: Vec<CodeSymbol>,
}

pub fn format_bytes(bytes: u64) -> String {
    const KB: u64 = 1024;
    const MB: u64 = 1024 * 1024;
    const GB: u64 = 1024 * 1024 * 1024;

    if bytes >= GB {
        format!("{:.2} GB", bytes as f64 / GB as f64)
    } else if bytes >= MB {
        format!("{:.2} MB", bytes as f64 / MB as f64)
    } else if bytes >= KB {
        format!("{:.1} KB", bytes as f64 / KB as f64)
    } else {
        format!("{} B", bytes)
    }
}

pub fn get_dir_size_and_count(dir: &Path) -> (u64, usize) {
    let mut total_size = 0;
    let mut file_count = 0;
    for entry in WalkDir::new(dir).into_iter().filter_map(|e| e.ok()) {
        if entry.file_type().is_file() {
            file_count += 1;
            if let Ok(meta) = entry.metadata() {
                total_size += meta.len();
            }
        }
    }
    (total_size, file_count)
}

pub fn detect_license(dir: &Path) -> Option<String> {
    let candidates = [
        "LICENSE",
        "LICENSE.txt",
        "LICENSE.md",
        "LICENSE.rst",
        "COPYING",
        "COPYING.txt",
    ];
    for name in &candidates {
        let p = dir.join(name);
        if p.is_file() {
            if let Ok(content) = std::fs::read_to_string(&p) {
                for line in content.lines() {
                    let trimmed = line.trim();
                    if !trimmed.is_empty() {
                        return Some(trimmed.to_string());
                    }
                }
            }
        }
    }
    None
}

pub fn detect_lib_description(dir: &Path) -> (Option<String>, Option<String>) {
    let mut version = None;
    let mut description = None;

    // Check CMakeLists.txt
    let cmake_file = dir.join("CMakeLists.txt");
    if cmake_file.is_file() {
        if let Ok(content) = std::fs::read_to_string(&cmake_file) {
            for line in content.lines() {
                let lower = line.to_lowercase();
                if lower.contains("project(") || lower.contains("project (") {
                    if let Some(v_idx) = lower.find("version") {
                        let after_v = &line[v_idx + 7..];
                        if let Some(v) = after_v.split_whitespace().next() {
                            let clean_v = v.trim_matches(|c: char| !c.is_alphanumeric() && c != '.');
                            if !clean_v.is_empty() {
                                version = Some(clean_v.to_string());
                            }
                        }
                    }
                    if let Some(d_idx) = lower.find("description") {
                        let after_d = &line[d_idx + 11..];
                        if let Some(first_quote) = after_d.find('"') {
                            if let Some(second_quote) = after_d[first_quote + 1..].find('"') {
                                description = Some(
                                    after_d[first_quote + 1..first_quote + 1 + second_quote]
                                        .to_string(),
                                );
                            }
                        }
                    }
                }
            }
        }
    }

    // Fallback to README
    if description.is_none() {
        for readme_name in &["README.md", "README.rst", "README.txt", "README"] {
            let readme_file = dir.join(readme_name);
            if readme_file.is_file() {
                if let Ok(content) = std::fs::read_to_string(&readme_file) {
                    for line in content.lines() {
                        let trimmed = line.trim();
                        if !trimmed.is_empty()
                            && !trimmed.starts_with('#')
                            && !trimmed.starts_with('[')
                            && !trimmed.starts_with("```")
                        {
                            description = Some(trimmed.to_string());
                            break;
                        }
                    }
                }
            }
            if description.is_some() {
                break;
            }
        }
    }

    (version, description)
}

pub fn count_headers(dir: &Path) -> usize {
    let mut count = 0;
    for entry in WalkDir::new(dir).into_iter().filter_map(|e| e.ok()) {
        if entry.file_type().is_file() {
            if let Some(ext) = entry.path().extension().and_then(|s| s.to_str()) {
                if ["h", "hpp", "hxx", "h++"].contains(&ext) {
                    count += 1;
                }
            }
        }
    }
    count
}

pub fn find_fetched_dep_dir(project_dir: &Path, dep_name: &str) -> Option<PathBuf> {
    let deps_root = project_dir.join("build").join("_deps");
    if !deps_root.is_dir() {
        return None;
    }

    let direct_candidates = [
        format!("{}-src", dep_name.to_lowercase()),
        format!("{}-src", dep_name),
        format!("{}_src", dep_name.to_lowercase()),
    ];

    for name in &direct_candidates {
        let p = deps_root.join(name);
        if p.is_dir() {
            return Some(p);
        }
    }

    if let Ok(entries) = deps_root.read_dir() {
        for entry in entries.flatten() {
            let file_name = entry.file_name().to_string_lossy().to_string();
            let lower = file_name.to_lowercase();
            if lower.contains(&dep_name.to_lowercase())
                && lower.ends_with("-src")
                && entry.path().is_dir()
            {
                return Some(entry.path());
            }
        }
    }

    None
}

pub fn find_built_target_info(
    project_dir: &Path,
    target_name: &str,
    is_bin: bool,
) -> Option<(String, u64)> {
    let build_dir = project_dir.join("build");
    if !build_dir.is_dir() {
        return None;
    }

    let possible_names = if is_bin {
        vec![target_name.to_string(), format!("{}.exe", target_name)]
    } else {
        vec![
            format!("lib{}.a", target_name),
            format!("lib{}.so", target_name),
            format!("{}.lib", target_name),
            format!("{}.dll", target_name),
            format!("lib{}.dylib", target_name),
        ]
    };

    for name in &possible_names {
        let candidate = build_dir.join(name);
        if candidate.is_file() {
            if let Ok(meta) = candidate.metadata() {
                return Some((format!("build/{}", name), meta.len()));
            }
        }
        for sub in &["Debug", "Release", "RelWithDebInfo"] {
            let sub_cand = build_dir.join(sub).join(name);
            if sub_cand.is_file() {
                if let Ok(meta) = sub_cand.metadata() {
                    return Some((format!("build/{}/{}", sub, name), meta.len()));
                }
            }
        }
    }

    None
}

fn extract_type_symbol(line: &str, line_num: usize, doc_lines: &[String]) -> Option<CodeSymbol> {
    if line.ends_with(';') && !line.contains('{') {
        return None;
    }

    let tokens: Vec<&str> = line.split_whitespace().collect();
    for (i, &tok) in tokens.iter().enumerate() {
        if (tok == "class" || tok == "struct") && i + 1 < tokens.len() {
            let next_tok = tokens[i + 1].trim_matches(|c: char| !c.is_alphanumeric() && c != '_');
            if !next_tok.is_empty() && next_tok != "alignas" {
                let kind = if tok == "class" {
                    SymbolKind::Class
                } else {
                    SymbolKind::Struct
                };
                let doc = if doc_lines.is_empty() {
                    None
                } else {
                    Some(doc_lines.join(" "))
                };
                let sig = line.trim_end_matches('{').trim().to_string();
                return Some(CodeSymbol {
                    kind,
                    name: next_tok.to_string(),
                    signature: sig,
                    line: line_num,
                    doc,
                });
            }
        } else if tok == "enum" && i + 1 < tokens.len() {
            let next_idx = if tokens[i + 1] == "class" || tokens[i + 1] == "struct" {
                i + 2
            } else {
                i + 1
            };
            if next_idx < tokens.len() {
                let name = tokens[next_idx].trim_matches(|c: char| !c.is_alphanumeric() && c != '_');
                if !name.is_empty() {
                    let doc = if doc_lines.is_empty() {
                        None
                    } else {
                        Some(doc_lines.join(" "))
                    };
                    let sig = line.trim_end_matches('{').trim().to_string();
                    return Some(CodeSymbol {
                        kind: SymbolKind::Enum,
                        name: name.to_string(),
                        signature: sig,
                        line: line_num,
                        doc,
                    });
                }
            }
        } else if tok == "namespace" && i + 1 < tokens.len() {
            let name = tokens[i + 1].trim_matches(|c: char| !c.is_alphanumeric() && c != '_' && c != ':');
            if !name.is_empty() && name != "{" {
                let doc = if doc_lines.is_empty() {
                    None
                } else {
                    Some(doc_lines.join(" "))
                };
                return Some(CodeSymbol {
                    kind: SymbolKind::Namespace,
                    name: name.to_string(),
                    signature: format!("namespace {}", name),
                    line: line_num,
                    doc,
                });
            }
        }
    }
    None
}

fn extract_function_symbol(
    line: &str,
    line_num: usize,
    doc_lines: &[String],
) -> Option<CodeSymbol> {
    if line.trim_start().starts_with('#') {
        return None;
    }

    let open_paren = line.find('(')?;
    let close_paren = line.rfind(')')?;
    if close_paren <= open_paren {
        return None;
    }

    let prefix = line[..open_paren].trim();
    if prefix.is_empty() {
        return None;
    }

    let last_word = prefix
        .split(|c: char| !c.is_alphanumeric() && c != '_' && c != ':')
        .rfind(|s| !s.is_empty())?;

    const KEYWORDS: &[&str] = &[
        "if", "else", "while", "for", "do", "switch", "catch", "case", "return", "sizeof",
        "decltype", "alignas", "static_assert", "typeid", "new", "delete", "throw",
    ];

    if KEYWORDS.contains(&last_word) {
        return None;
    }

    let sig_end = line.find('{').unwrap_or(line.len());
    let sig = line[..sig_end].trim().trim_end_matches(';').trim().to_string();

    let doc = if doc_lines.is_empty() {
        None
    } else {
        Some(doc_lines.join(" "))
    };

    Some(CodeSymbol {
        kind: SymbolKind::Function,
        name: last_word.to_string(),
        signature: sig,
        line: line_num,
        doc,
    })
}

pub fn analyze_source_file(project_dir: &Path, rel_path: &Path) -> Option<FileMetrics> {
    let full_path = project_dir.join(rel_path);
    let content = std::fs::read_to_string(&full_path).ok()?;
    let metadata = std::fs::metadata(&full_path).ok()?;
    let size_bytes = metadata.len();

    let mut total_lines = 0;
    let mut code_lines = 0;
    let mut comment_lines = 0;
    let mut blank_lines = 0;
    let mut in_block_comment = false;

    let mut pending_doc: Vec<String> = Vec::new();
    let mut symbols = Vec::new();

    let lines: Vec<&str> = content.lines().collect();

    for (idx, line) in lines.iter().enumerate() {
        total_lines += 1;
        let line_num = idx + 1;
        let trimmed = line.trim();

        if trimmed.is_empty() {
            blank_lines += 1;
            pending_doc.clear();
            continue;
        }

        if in_block_comment {
            comment_lines += 1;
            if let Some(doc_text) = trimmed.strip_prefix('*') {
                let clean = doc_text.trim();
                if !clean.is_empty() && clean != "/" {
                    pending_doc.push(clean.to_string());
                }
            }
            if trimmed.contains("*/") {
                in_block_comment = false;
            }
            continue;
        }

        if trimmed.starts_with("/*") {
            comment_lines += 1;
            if !trimmed.contains("*/") {
                in_block_comment = true;
            }
            if let Some(doc_text) = trimmed.strip_prefix("/**").or_else(|| trimmed.strip_prefix("/*")) {
                let clean = doc_text.trim_end_matches("*/").trim();
                if !clean.is_empty() {
                    pending_doc.push(clean.to_string());
                }
            }
            continue;
        }

        if trimmed.starts_with("//") {
            comment_lines += 1;
            let doc_text = trimmed
                .strip_prefix("///")
                .unwrap_or_else(|| trimmed.strip_prefix("//").unwrap_or(""));
            let clean = doc_text.trim();
            if !clean.is_empty() {
                pending_doc.push(clean.to_string());
            }
            continue;
        }

        code_lines += 1;

        if let Some(sym) = extract_type_symbol(trimmed, line_num, &pending_doc) {
            symbols.push(sym);
            pending_doc.clear();
            continue;
        }

        if let Some(sym) = extract_function_symbol(trimmed, line_num, &pending_doc) {
            symbols.push(sym);
            pending_doc.clear();
            continue;
        }

        if !trimmed.starts_with('#') && !trimmed.starts_with('{') && !trimmed.starts_with('}') {
            pending_doc.clear();
        }
    }

    Some(FileMetrics {
        path: rel_path.to_string_lossy().replace('\\', "/"),
        total_lines,
        code_lines,
        comment_lines,
        blank_lines,
        size_bytes,
        symbols,
    })
}

pub fn generate_docs(project_dir: &Path) -> Result<String> {
    let config_path = project_dir.join("catch.toml");
    if !config_path.exists() {
        return Err(anyhow!("catch.toml not found in {}", project_dir.display()));
    }

    let cfg = parse_config(&config_path)?;
    let lock_data = load_lock(&project_dir.join("catch.lock"));

    let collect_files = |dir_name: &str| -> Vec<String> {
        let dir = project_dir.join(dir_name);
        let mut files = Vec::new();
        if dir.exists() {
            for entry in WalkDir::new(&dir).into_iter().filter_map(|e| e.ok()) {
                if entry.file_type().is_file() {
                    if let Ok(rel) = entry.path().strip_prefix(project_dir) {
                        files.push(rel.to_string_lossy().replace('\\', "/"));
                    }
                }
            }
        }
        files.sort();
        files
    };

    let src_files = collect_files("src");
    let inc_files = collect_files("include");
    let test_files = collect_files("tests");

    // Analyze all source and header files
    let mut all_code_files = Vec::new();
    all_code_files.extend(src_files.iter().cloned());
    all_code_files.extend(inc_files.iter().cloned());
    all_code_files.extend(test_files.iter().cloned());

    let mut file_analyses = Vec::new();
    let mut total_sloc = 0;
    let mut total_comments = 0;
    let mut total_blank = 0;
    let mut total_lines = 0;
    let mut total_source_size = 0;

    for f in &all_code_files {
        let p = Path::new(f);
        if let Some(ext) = p.extension().and_then(|e| e.to_str()) {
            if ["cpp", "cc", "c", "cu", "cxx", "h", "hpp", "hxx", "h++"].contains(&ext) {
                if let Some(metrics) = analyze_source_file(project_dir, p) {
                    total_sloc += metrics.code_lines;
                    total_comments += metrics.comment_lines;
                    total_blank += metrics.blank_lines;
                    total_lines += metrics.total_lines;
                    total_source_size += metrics.size_bytes;
                    file_analyses.push(metrics);
                }
            }
        }
    }

    let is_bin = cfg.package.r#type == "bin";
    let built_info = find_built_target_info(project_dir, &cfg.package.name, is_bin);
    let build_dir_stats = if project_dir.join("build").is_dir() {
        Some(get_dir_size_and_count(&project_dir.join("build")))
    } else {
        None
    };

    let mut lines = vec![
        GENERATED_NOTE.trim_end().to_string(),
        format!("# Project: {}", cfg.package.name),
        "".to_string(),
        format!("- **Version**: `{}`", cfg.package.version),
        format!("- **Type**: `{}`", cfg.package.r#type),
        "".to_string(),
        "## Project Details & Code Metrics".to_string(),
        format!("- **Total Source Files**: {} files", file_analyses.len()),
        format!(
            "- **Total Lines of Code**: {} lines ({} code, {} comments, {} blank)",
            total_lines, total_sloc, total_comments, total_blank
        ),
        format!(
            "- **Total Source Tree Size**: {}",
            format_bytes(total_source_size)
        ),
    ];

    if let Some((built_path, built_size)) = built_info {
        lines.push(format!(
            "- **Built Artifact**: `{}` ({})",
            built_path,
            format_bytes(built_size)
        ));
    }

    if let Some((build_size, build_files)) = build_dir_stats {
        lines.push(format!(
            "- **Build Directory**: `build/` ({} across {} files)",
            format_bytes(build_size),
            build_files
        ));
    }

    lines.push("".to_string());
    lines.push("## Languages and Standard".to_string());
    lines.push(format!("- **Languages**: {}", cfg.build.languages.join(", ")));
    lines.push(format!("- **C++ Standard**: `{}`", cfg.build.std));
    lines.push(format!("- **Compile Flags**: `{:?}`", cfg.build.flags));
    lines.push(format!("- **Defines**: `{:?}`", cfg.build.defines));
    lines.push(format!("- **Release Flags**: `{:?}`", cfg.build.release_flags));
    lines.push("".to_string());

    lines.push("## Source Tree".to_string());
    if !src_files.is_empty() {
        lines.push("### Source Files (`src/`)".to_string());
        for f in &src_files {
            lines.push(format!("- `{}`", f));
        }
    }

    if !inc_files.is_empty() {
        lines.push("### Header Files (`include/`)".to_string());
        for f in &inc_files {
            lines.push(format!("- `{}`", f));
        }
    }

    if !test_files.is_empty() {
        lines.push("### Test Files (`tests/`)".to_string());
        for f in &test_files {
            lines.push(format!("- `{}`", f));
        }
    }

    lines.push("".to_string());
    lines.push("## Targets".to_string());
    lines.push(format!(
        "- **Main Target**: `{}` ({})",
        cfg.package.name, cfg.package.r#type
    ));
    if !test_files.is_empty() {
        lines.push("- **Test Executables**:".to_string());
        for tf in &test_files {
            let stem = Path::new(tf)
                .file_stem()
                .unwrap_or_default()
                .to_string_lossy();
            lines.push(format!("  - `test_{}` (from `{}`)", stem, tf));
        }
    }

    lines.push("".to_string());
    lines.push("## Dependencies & Pulled Libraries".to_string());
    if !cfg.dependencies.is_empty() {
        for (name, dep) in &cfg.dependencies {
            let locked = lock_data.dependencies.get(name);
            let ref_str = dep
                .tag
                .as_deref()
                .or(dep.branch.as_deref())
                .or(dep.rev.as_deref())
                .unwrap_or("HEAD");
            let commit = locked.map(|d| d.commit.as_str()).unwrap_or("unlocked");
            let target = dep
                .target
                .clone()
                .unwrap_or_else(|| format!("{}::{}", name, name));

            lines.push(format!("### Library: `{}`", name));
            lines.push(format!("- **Repository URL**: `{}`", dep.git));
            lines.push(format!("- **Requested Ref**: `{}`", ref_str));
            lines.push(format!("- **Locked Commit**: `{}`", commit));
            lines.push(format!("- **CMake Target**: `{}`", target));

            // Check if dependency has been fetched into build/_deps
            if let Some(dep_dir) = find_fetched_dep_dir(project_dir, name) {
                let (dep_size, dep_files) = get_dir_size_and_count(&dep_dir);
                let license = detect_license(&dep_dir);
                let (lib_version, lib_desc) = detect_lib_description(&dep_dir);
                let header_count = count_headers(&dep_dir);

                let rel_dep_dir = dep_dir
                    .strip_prefix(project_dir)
                    .unwrap_or(&dep_dir)
                    .to_string_lossy()
                    .replace('\\', "/");

                lines.push("- **Fetch Status**: `Fetched & Cached`".to_string());
                lines.push(format!("- **Local Cache Path**: `{}`", rel_dep_dir));
                lines.push(format!(
                    "- **Pulled Size**: {} across {} files",
                    format_bytes(dep_size),
                    dep_files
                ));
                if header_count > 0 {
                    lines.push(format!("- **Headers Found**: {} header files", header_count));
                }
                if let Some(lic) = license {
                    lines.push(format!("- **Detected License**: `{}`", lic));
                }
                if let Some(ver) = lib_version {
                    lines.push(format!("- **Library Version**: `{}`", ver));
                }
                if let Some(desc) = lib_desc {
                    lines.push(format!("- **Description**: {}", desc));
                }
            } else {
                lines.push(
                    "- **Fetch Status**: `Declared (run 'catch build' to fetch and cache)`"
                        .to_string(),
                );
            }
            lines.push("".to_string());
        }
    } else {
        lines.push("No dependencies declared.".to_string());
    }

    // Source Code Analysis & Extracted Functions/Symbols
    if !file_analyses.is_empty() {
        lines.push("".to_string());
        lines.push("## Source Code Analysis & API Overview".to_string());
        lines.push("".to_string());
        lines.push("| File | Total Lines | Code Lines | Comments | Blank | Size | Symbols |".to_string());
        lines.push("| :--- | :---: | :---: | :---: | :---: | :---: | :---: |".to_string());
        for fa in &file_analyses {
            lines.push(format!(
                "| `{}` | {} | {} | {} | {} | {} | {} |",
                fa.path,
                fa.total_lines,
                fa.code_lines,
                fa.comment_lines,
                fa.blank_lines,
                format_bytes(fa.size_bytes),
                fa.symbols.len()
            ));
        }

        // Detailed extracted symbols per file
        let files_with_symbols: Vec<_> = file_analyses.iter().filter(|f| !f.symbols.is_empty()).collect();
        if !files_with_symbols.is_empty() {
            lines.push("".to_string());
            lines.push("### Extracted Functions & Symbols".to_string());
            for fa in files_with_symbols {
                lines.push("".to_string());
                lines.push(format!(
                    "#### `{}` ({} lines, {})",
                    fa.path,
                    fa.total_lines,
                    format_bytes(fa.size_bytes)
                ));
                for sym in &fa.symbols {
                    lines.push(format!(
                        "- **{}** `{}`: `{}` *(line {})*",
                        sym.kind.as_str(),
                        sym.name,
                        sym.signature,
                        sym.line
                    ));
                    if let Some(ref doc) = sym.doc {
                        lines.push(format!("  - *Doc*: {}", doc));
                    }
                }
            }
        }
    }

    if let Some(ref cuda) = cfg.cuda {
        lines.push("".to_string());
        lines.push("## CUDA Settings".to_string());
        lines.push(format!("- **Architectures**: `{:?}`", cuda.arch));
        lines.push(format!("- **CUDA Standard**: `{}`", cuda.std));
        lines.push(format!("- **Flags**: `{:?}`", cuda.flags));
        lines.push(format!("- **Separable Compilation**: `{}`", cuda.separable));
    }

    if let Some(ref llvm) = cfg.llvm {
        lines.push("".to_string());
        lines.push("## LLVM & MLIR Settings".to_string());
        lines.push(format!("- **LLVM Dir**: `{:?}`", llvm.dir));
        lines.push(format!("- **MLIR Enabled**: `{}`", llvm.mlir));
        if let Some(ref mlir_dir) = llvm.mlir_dir {
            lines.push(format!("- **MLIR Dir**: `{}`", mlir_dir));
        }
        lines.push(format!("- **Components**: `{:?}`", llvm.components));
        if !llvm.mlir_libs.is_empty() {
            lines.push(format!("- **MLIR Libraries**: `{:?}`", llvm.mlir_libs));
        }
    }

    lines.push("".to_string());
    lines.push("## Build Commands".to_string());
    lines.push("Commands run by `catch` for this project:".to_string());
    lines.push("```sh".to_string());
    lines.push("cmake -S . -B build -G Ninja -DCMAKE_BUILD_TYPE=Debug".to_string());
    lines.push("cmake --build build".to_string());
    lines.push("ctest --test-dir build --output-on-failure".to_string());
    lines.push("```".to_string());

    lines.push("".to_string());
    lines.push("## Catch Commands Help".to_string());
    lines.push("- `catch new <name> [--cuda] [--mlir]`: Creates a new C++ project.".to_string());
    lines.push("- `catch build [--release]`: Regenerates CMakeLists.txt and compiles the project.".to_string());
    lines.push("- `catch run [-- args]`: Builds and executes the main project binary.".to_string());
    lines.push("- `catch test`: Builds and runs all tests using CTest.".to_string());
    lines.push("- `catch clean`: Deletes the build/ directory.".to_string());
    lines.push("- `catch add <url> [--tag|--branch|--rev] [--name] [--target]`: Adds a git dependency.".to_string());
    lines.push("- `catch remove <name>`: Removes a dependency from catch.toml.".to_string());
    lines.push("- `catch update [name]`: Re-resolves git dependency commit hashes in catch.lock.".to_string());
    lines.push("- `catch docs [--stdout]`: Generates docs/PROJECT.md documentation.".to_string());
    lines.push("- `catch doctor`: Checks for required toolchain dependencies and system setup.".to_string());
    lines.push("- `catch cmake [path] [--release] [--target <name>]`: Detects an existing CMakeLists.txt and builds it with CMake.".to_string());

    Ok(lines.join("\n") + "\n")
}

pub fn cmd_docs(stdout: bool) -> Result<()> {
    let project_dir = std::env::current_dir()?;
    let content = generate_docs(&project_dir)?;

    if stdout {
        print!("{}", content);
    } else {
        let docs_dir = project_dir.join("docs");
        std::fs::create_dir_all(&docs_dir)?;
        let doc_file = docs_dir.join("PROJECT.md");
        std::fs::write(&doc_file, content)?;
        println!(
            "Wrote documentation to {}",
            doc_file
                .strip_prefix(&project_dir)
                .unwrap_or(&doc_file)
                .display()
        );
    }

    Ok(())
}
