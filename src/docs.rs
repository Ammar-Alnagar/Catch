use anyhow::{anyhow, Result};
use std::path::Path;
use walkdir::WalkDir;

use crate::config::parse_config;
use crate::lock::load_lock;

pub const GENERATED_NOTE: &str = "<!-- Generated by catch docs. Do not edit directly. -->\n";

pub fn generate_docs(project_dir: &Path) -> Result<String> {
    let config_path = project_dir.join("catch.toml");
    if !config_path.exists() {
        return Err(anyhow!("catch.toml not found in {}", project_dir.display()));
    }

    let cfg = parse_config(&config_path)?;
    let lock_data = load_lock(&project_dir.join("catch.lock"));

    let mut lines = vec![
        GENERATED_NOTE.trim_end().to_string(),
        format!("# Project: {}", cfg.package.name),
        "".to_string(),
        format!("- **Version**: `{}`", cfg.package.version),
        format!("- **Type**: `{}`", cfg.package.r#type),
        "".to_string(),
        "## Languages and Standard".to_string(),
        format!("- **Languages**: {}", cfg.build.languages.join(", ")),
        format!("- **C++ Standard**: `{}`", cfg.build.std),
        format!("- **Compile Flags**: `{:?}`", cfg.build.flags),
        format!("- **Defines**: `{:?}`", cfg.build.defines),
        format!("- **Release Flags**: `{:?}`", cfg.build.release_flags),
        "".to_string(),
        "## Source Tree".to_string(),
    ];

    let collect_files = |dir_name: &str| -> Vec<String> {
        let dir = project_dir.join(dir_name);
        let mut files = Vec::new();
        if dir.exists() {
            for entry in WalkDir::new(&dir).into_iter().filter_map(|e| e.ok()) {
                if entry.file_type().is_file() {
                    if let Ok(rel) = entry.path().strip_prefix(project_dir) {
                        files.push(rel.to_string_lossy().replace('\\', "/"));
                    }
                }
            }
        }
        files.sort();
        files
    };

    let src_files = collect_files("src");
    let inc_files = collect_files("include");
    let test_files = collect_files("tests");

    if !src_files.is_empty() {
        lines.push("### Source Files (`src/`)".to_string());
        for f in &src_files {
            lines.push(format!("- `{}`", f));
        }
    }

    if !inc_files.is_empty() {
        lines.push("### Header Files (`include/`)".to_string());
        for f in &inc_files {
            lines.push(format!("- `{}`", f));
        }
    }

    if !test_files.is_empty() {
        lines.push("### Test Files (`tests/`)".to_string());
        for f in &test_files {
            lines.push(format!("- `{}`", f));
        }
    }

    lines.push("".to_string());
    lines.push("## Targets".to_string());
    lines.push(format!("- **Main Target**: `{}` ({})", cfg.package.name, cfg.package.r#type));
    if !test_files.is_empty() {
        lines.push("- **Test Executables**:".to_string());
        for tf in &test_files {
            let stem = Path::new(tf).file_stem().unwrap_or_default().to_string_lossy();
            lines.push(format!("  - `test_{}` (from `{}`)", stem, tf));
        }
    }

    lines.push("".to_string());
    lines.push("## Dependencies".to_string());
    if !cfg.dependencies.is_empty() {
        for (name, dep) in &cfg.dependencies {
            let locked = lock_data.dependencies.get(name);
            let ref_str = dep
                .tag
                .as_deref()
                .or(dep.branch.as_deref())
                .or(dep.rev.as_deref())
                .unwrap_or("HEAD");
            let commit = locked.map(|d| d.commit.as_str()).unwrap_or("unlocked");
            let target = dep.target.clone().unwrap_or_else(|| format!("{}::{}", name, name));

            lines.push(format!("- **{}**", name));
            lines.push(format!("  - URL: `{}`", dep.git));
            lines.push(format!("  - Requested Ref: `{}`", ref_str));
            lines.push(format!("  - Locked Commit: `{}`", commit));
            lines.push(format!("  - Target: `{}`", target));
        }
    } else {
        lines.push("No dependencies declared.".to_string());
    }

    if let Some(ref cuda) = cfg.cuda {
        lines.push("".to_string());
        lines.push("## CUDA Settings".to_string());
        lines.push(format!("- **Architectures**: `{:?}`", cuda.arch));
        lines.push(format!("- **CUDA Standard**: `{}`", cuda.std));
        lines.push(format!("- **Flags**: `{:?}`", cuda.flags));
        lines.push(format!("- **Separable Compilation**: `{}`", cuda.separable));
    }

    if let Some(ref llvm) = cfg.llvm {
        lines.push("".to_string());
        lines.push("## LLVM & MLIR Settings".to_string());
        lines.push(format!("- **LLVM Dir**: `{:?}`", llvm.dir));
        lines.push(format!("- **MLIR Enabled**: `{}`", llvm.mlir));
        if let Some(ref mlir_dir) = llvm.mlir_dir {
            lines.push(format!("- **MLIR Dir**: `{}`", mlir_dir));
        }
        lines.push(format!("- **Components**: `{:?}`", llvm.components));
        if !llvm.mlir_libs.is_empty() {
            lines.push(format!("- **MLIR Libraries**: `{:?}`", llvm.mlir_libs));
        }
    }

    lines.push("".to_string());
    lines.push("## Build Commands".to_string());
    lines.push("Commands run by `catch` for this project:".to_string());
    lines.push("```sh".to_string());
    lines.push("cmake -S . -B build -G Ninja -DCMAKE_BUILD_TYPE=Debug".to_string());
    lines.push("cmake --build build".to_string());
    lines.push("ctest --test-dir build --output-on-failure".to_string());
    lines.push("```".to_string());

    lines.push("".to_string());
    lines.push("## Catch Commands Help".to_string());
    lines.push("- `catch new <name> [--cuda] [--mlir]`: Creates a new C++ project.".to_string());
    lines.push("- `catch build [--release]`: Regenerates CMakeLists.txt and compiles the project.".to_string());
    lines.push("- `catch run [-- args]`: Builds and executes the main project binary.".to_string());
    lines.push("- `catch test`: Builds and runs all tests using CTest.".to_string());
    lines.push("- `catch clean`: Deletes the build/ directory.".to_string());
    lines.push("- `catch add <url> [--tag|--branch|--rev] [--name] [--target]`: Adds a git dependency.".to_string());
    lines.push("- `catch remove <name>`: Removes a dependency from catch.toml.".to_string());
    lines.push("- `catch update [name]`: Re-resolves git dependency commit hashes in catch.lock.".to_string());
    lines.push("- `catch docs [--stdout]`: Generates docs/PROJECT.md documentation.".to_string());
    lines.push("- `catch doctor`: Checks for required toolchain dependencies and system setup.".to_string());

    Ok(lines.join("\n") + "\n")
}

pub fn cmd_docs(stdout: bool) -> Result<()> {
    let project_dir = std::env::current_dir()?;
    let content = generate_docs(&project_dir)?;

    if stdout {
        print!("{}", content);
    } else {
        let docs_dir = project_dir.join("docs");
        std::fs::create_dir_all(&docs_dir)?;
        let doc_file = docs_dir.join("PROJECT.md");
        std::fs::write(&doc_file, content)?;
        println!(
            "Wrote documentation to {}",
            doc_file.strip_prefix(&project_dir).unwrap_or(&doc_file).display()
        );
    }

    Ok(())
}
