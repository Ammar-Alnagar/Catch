use std::path::Path;
use walkdir::WalkDir;

use crate::config::CatchConfig;
use crate::lock::LockData;

pub const HEADER_COMMENT: &str = "# Generated by catch. Do not edit.\n";

pub fn generate_cmakelists(config: &CatchConfig, project_dir: &Path, lock_data: Option<&LockData>) -> String {
    let mut lines = vec![
        HEADER_COMMENT.trim_end().to_string(),
        "cmake_minimum_required(VERSION 3.24)".to_string(),
    ];

    let langs = config.build.languages.join(" ");
    lines.push(format!("project({} LANGUAGES {})", config.package.name, langs));
    lines.push("".to_string());

    lines.push("set(CMAKE_EXPORT_COMPILE_COMMANDS ON)".to_string());
    if config.build.languages.contains(&"CXX".to_string()) {
        lines.push(format!("set(CMAKE_CXX_STANDARD {})", config.build.std));
        lines.push("set(CMAKE_CXX_STANDARD_REQUIRED ON)".to_string());
    }

    // Build flags
    if !config.build.flags.is_empty() {
        let flags_str = config.build.flags.join(" ");
        lines.push(format!("add_compile_options({})", flags_str));
    }

    if !config.build.defines.is_empty() {
        for d in &config.build.defines {
            lines.push(format!("add_compile_definitions({})", d));
        }
    }

    // Release flags
    if !config.build.release_flags.is_empty() {
        let rel_flags_str = config.build.release_flags.join(" ");
        lines.push(format!("string(APPEND CMAKE_CXX_FLAGS_RELEASE \" {}\")", rel_flags_str));
    }

    lines.push("".to_string());

    // CUDA settings
    if config.build.languages.contains(&"CUDA".to_string()) {
        lines.push("find_package(CUDAToolkit REQUIRED)".to_string());
        if let Some(ref cuda) = config.cuda {
            lines.push("enable_language(CUDA)".to_string());
            lines.push(format!("set(CMAKE_CUDA_STANDARD {})", cuda.std));
            lines.push("set(CMAKE_CUDA_STANDARD_REQUIRED ON)".to_string());
            if !cuda.arch.is_empty() {
                let arch_str = cuda.arch.join(";");
                lines.push(format!("if(NOT DEFINED CMAKE_CUDA_ARCHITECTURES)\n  set(CMAKE_CUDA_ARCHITECTURES \"{}\")\nendif()", arch_str));
            }
            if !cuda.flags.is_empty() {
                let cflags = cuda.flags.join(" ");
                lines.push(format!("add_compile_options($<$<COMPILE_LANGUAGE:CUDA>:{}>)", cflags));
            }
            if cuda.separable {
                lines.push("set(CMAKE_CUDA_SEPARABLE_COMPILATION ON)".to_string());
            }
            lines.push("".to_string());
        }
    }

    // LLVM & MLIR settings
    if let Some(ref llvm) = config.llvm {
        lines.push("# LLVM & MLIR configuration".to_string());
        lines.push("find_package(LLVM REQUIRED CONFIG)".to_string());
        lines.push("message(STATUS \"Using LLVMConfig.cmake in ${LLVM_DIR}\")".to_string());
        if llvm.mlir {
            lines.push("find_package(MLIR REQUIRED CONFIG)".to_string());
            lines.push("message(STATUS \"Using MLIRConfig.cmake in ${MLIR_DIR}\")".to_string());
        }

        lines.push("list(APPEND CMAKE_MODULE_PATH \"${LLVM_CMAKE_DIR}\")".to_string());
        if llvm.mlir {
            lines.push("list(APPEND CMAKE_MODULE_PATH \"${MLIR_CMAKE_DIR}\")".to_string());
        }

        lines.push("include(TableGen)".to_string());
        lines.push("include(AddLLVM)".to_string());
        if llvm.mlir {
            lines.push("include(AddMLIR)".to_string());
        }
        lines.push("include(HandleLLVMOptions)".to_string());

        lines.push("include_directories(${LLVM_INCLUDE_DIRS})".to_string());
        if llvm.mlir {
            lines.push("include_directories(${MLIR_INCLUDE_DIRS})".to_string());
        }

        lines.push("add_definitions(${LLVM_DEFINITIONS})".to_string());

        // RTTI check
        lines.push("if(NOT LLVM_ENABLE_RTTI)\n  if(MSVC)\n    add_compile_options(/GR-)\n  else()\n    add_compile_options(-fno-rtti)\n  endif()\nendif()".to_string());
        lines.push("".to_string());
    }

    // FetchContent dependencies
    if !config.dependencies.is_empty() {
        lines.push("include(FetchContent)".to_string());
        let empty_map = std::collections::BTreeMap::new();
        let lock_deps = lock_data.map(|d| &d.dependencies).unwrap_or(&empty_map);

        for (dep_name, dep) in &config.dependencies {
            let locked_commit = lock_deps.get(dep_name).map(|d| d.commit.as_str());
            let tag_to_use = locked_commit
                .or(dep.tag.as_deref())
                .or(dep.branch.as_deref())
                .or(dep.rev.as_deref())
                .unwrap_or("HEAD");

            lines.push(format!(
                "FetchContent_Declare(\n  {}\n  GIT_REPOSITORY {}\n  GIT_TAG {}\n)",
                dep_name, dep.git, tag_to_use
            ));
            lines.push(format!("FetchContent_MakeAvailable({})", dep_name));

            let target = dep.target.clone().unwrap_or_else(|| format!("{}::{}", dep_name, dep_name));

            lines.push(format!("if(TARGET {})\n  set({}_LINK_TARGET \"{}\")", target, dep_name, target));
            lines.push(format!("elseif(TARGET {})\n  set({}_LINK_TARGET \"{}\")", dep_name, dep_name, dep_name));
            lines.push(format!("else()\n  message(WARNING \"Target '{}' or '{}' for dependency '{}' not found after configure.\")", target, dep_name, dep_name));
            lines.push(format!("  set({}_LINK_TARGET \"{}\")\nendif()", dep_name, target));
            lines.push("".to_string());
        }
    }

    // Sources discovery
    let src_dir = project_dir.join("src");
    let mut sources = Vec::new();
    if src_dir.exists() {
        for entry in WalkDir::new(&src_dir).into_iter().filter_map(|e| e.ok()) {
            if entry.file_type().is_file() {
                if let Some(ext) = entry.path().extension().and_then(|s| s.to_str()) {
                    if ["cpp", "cc", "c", "cu"].contains(&ext) {
                        if let Ok(rel) = entry.path().strip_prefix(project_dir) {
                            sources.push(rel.to_string_lossy().replace('\\', "/"));
                        }
                    }
                }
            }
        }
    }

    sources.sort();

    let inc_dir = project_dir.join("include");
    let has_include = inc_dir.exists() && inc_dir.is_dir();

    // Targets (bin or lib)
    if config.package.r#type == "bin" {
        lines.push(format!("add_executable({})", config.package.name));
        if !sources.is_empty() {
            let sources_str = sources.join("\n  ");
            lines.push(format!("target_sources({} PRIVATE\n  {}\n)", config.package.name, sources_str));
        }
    } else {
        // lib: exclude main.cpp if present
        let lib_sources: Vec<_> = sources.into_iter().filter(|s| !s.ends_with("main.cpp")).collect();
        lines.push(format!("add_library({})", config.package.name));
        if !lib_sources.is_empty() {
            let sources_str = lib_sources.join("\n  ");
            lines.push(format!("target_sources({} PRIVATE\n  {}\n)", config.package.name, sources_str));
        }
    }

    if has_include {
        lines.push(format!("target_include_directories({} PUBLIC include)", config.package.name));
    }

    // Link dependencies
    if !config.dependencies.is_empty() {
        for dep_name in config.dependencies.keys() {
            lines.push(format!("target_link_libraries({} PRIVATE ${{{}_LINK_TARGET}})", config.package.name, dep_name));
        }
    }

    if config.build.languages.contains(&"CUDA".to_string()) {
        lines.push(format!("target_link_libraries({} PRIVATE CUDA::cudart)", config.package.name));
    }

    if let Some(ref llvm) = config.llvm {
        if !llvm.components.is_empty() {
            let comp_str = llvm.components.join(" ");
            lines.push(format!("llvm_map_components_to_libnames(llvm_libs {})", comp_str));
            lines.push(format!("target_link_libraries({} PRIVATE ${{llvm_libs}})", config.package.name));
        }
        if llvm.mlir && !llvm.mlir_libs.is_empty() {
            let mlir_lib_str = llvm.mlir_libs.join(" ");
            lines.push(format!("target_link_libraries({} PRIVATE {})", config.package.name, mlir_lib_str));
        }
    }

    lines.push("".to_string());

    // Tests discovery
    let tests_dir = project_dir.join("tests");
    let mut test_files = Vec::new();
    if tests_dir.exists() {
        for entry in WalkDir::new(&tests_dir).into_iter().filter_map(|e| e.ok()) {
            if entry.file_type().is_file() {
                if let Some(ext) = entry.path().extension().and_then(|s| s.to_str()) {
                    if ["cpp", "cc", "c", "cu"].contains(&ext) {
                        test_files.push(entry.path().to_path_buf());
                    }
                }
            }
        }
    }

    test_files.sort();

    if !test_files.is_empty() {
        lines.push("enable_testing()".to_string());
        for tf in test_files {
            let rel_tf = tf.strip_prefix(project_dir).unwrap_or(&tf).to_string_lossy().replace('\\', "/");
            let test_name = tf.file_stem().unwrap_or_default().to_string_lossy();
            let target_name = format!("test_{}", test_name);
            lines.push(format!("add_executable({} {})", target_name, rel_tf));
            if has_include {
                lines.push(format!("target_include_directories({} PRIVATE include)", target_name));
            }
            if config.package.r#type == "lib" {
                lines.push(format!("target_link_libraries({} PRIVATE {})", target_name, config.package.name));
            }
            if !config.dependencies.is_empty() {
                for dep_name in config.dependencies.keys() {
                    lines.push(format!("target_link_libraries({} PRIVATE ${{{}_LINK_TARGET}})", target_name, dep_name));
                }
            }
            lines.push(format!("add_test(NAME {} COMMAND {})", test_name, target_name));
        }
        lines.push("".to_string());
    }

    // extra.cmake inclusion
    let extra_cmake = project_dir.join("extra.cmake");
    if extra_cmake.exists() {
        lines.push("if(EXISTS \"${CMAKE_CURRENT_SOURCE_DIR}/extra.cmake\")".to_string());
        lines.push("  include(\"${CMAKE_CURRENT_SOURCE_DIR}/extra.cmake\")".to_string());
        lines.push("endif()".to_string());
    }

    lines.join("\n") + "\n"
}
