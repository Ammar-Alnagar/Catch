use anyhow::{anyhow, Result};
use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;
use std::path::Path;

use crate::config::parse_config;
use crate::runner::run_command;

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct LockDependency {
    pub url: String,
    #[serde(rename = "requested_ref")]
    pub ref_str: Option<String>,
    pub commit: String,
}

#[derive(Debug, Clone, Serialize, Deserialize, Default)]
pub struct LockData {
    #[serde(default)]
    pub dependencies: BTreeMap<String, LockDependency>,
}

pub fn resolve_git_commit(url: &str, ref_str: Option<&str>) -> Result<String> {
    let mut cmd = vec!["git", "ls-remote", url];
    if let Some(r) = ref_str {
        cmd.push(r);
    }

    let output_res = run_command(&cmd, None, false, true, true);
    let mut stdout = match output_res {
        Ok(out) => String::from_utf8_lossy(&out.stdout).trim().to_string(),
        Err(_) => String::new(),
    };

    if stdout.is_empty() {
        // Fallback to HEAD if ref returned nothing
        let fallback_res = run_command(&["git", "ls-remote", url, "HEAD"], None, false, true, true);
        if let Ok(out) = fallback_res {
            stdout = String::from_utf8_lossy(&out.stdout).trim().to_string();
        }
    }

    if stdout.is_empty() {
        return Err(anyhow!("Could not resolve commit hash for {} ref '{:?}'", url, ref_str));
    }

    let first_line = stdout.lines().next().unwrap_or_default();
    let commit_hash = first_line.split_whitespace().next().unwrap_or_default();

    if commit_hash.is_empty() {
        return Err(anyhow!("Could not resolve commit hash for {} ref '{:?}'", url, ref_str));
    }

    Ok(commit_hash.to_string())
}

pub fn load_lock(lock_path: &Path) -> LockData {
    if !lock_path.exists() {
        return LockData::default();
    }

    if let Ok(content) = std::fs::read_to_string(lock_path) {
        if let Ok(data) = toml::from_str(&content) {
            return data;
        }
    }

    LockData::default()
}

pub fn save_lock(lock_path: &Path, lock_data: &LockData) -> Result<()> {
    let mut lines = vec!["# Generated by catch. Do not edit.".to_string(), "".to_string()];

    for (name, dep) in &lock_data.dependencies {
        lines.push(format!("[dependencies.{}]", name));
        lines.push(format!("url = \"{}\"", dep.url));
        if let Some(ref r) = dep.ref_str {
            lines.push(format!("requested_ref = \"{}\"", r));
        }
        lines.push(format!("commit = \"{}\"", dep.commit));
        lines.push("".to_string());
    }

    std::fs::write(lock_path, lines.join("\n") + "\n")?;
    Ok(())
}

pub fn update_lock_for_project(project_dir: &Path, force_update_dep: Option<&str>) -> Result<LockData> {
    let config_path = project_dir.join("catch.toml");
    let cfg = parse_config(&config_path)?;

    let lock_path = project_dir.join("catch.lock");
    let lock_data = load_lock(&lock_path);

    let mut new_deps = BTreeMap::new();

    for (name, dep) in &cfg.dependencies {
        let ref_str = dep
            .tag
            .as_deref()
            .or(dep.branch.as_deref())
            .or(dep.rev.as_deref())
            .unwrap_or("HEAD");

        let existing_dep = lock_data.dependencies.get(name);
        let force_matches = match force_update_dep {
            Some(f) => f == name,
            None => force_update_dep.is_none(),
        };

        let needs_resolve = existing_dep.is_none()
            || force_matches
            || existing_dep.map(|d| d.url.as_str()) != Some(&dep.git)
            || existing_dep.and_then(|d| d.ref_str.as_deref()) != Some(ref_str);

        if needs_resolve {
            println!("Resolving dependency '{}' ({} @ {})...", name, dep.git, ref_str);
            let ref_to_pass = if ref_str != "HEAD" { Some(ref_str) } else { None };
            let commit = resolve_git_commit(&dep.git, ref_to_pass)?;
            new_deps.insert(
                name.clone(),
                LockDependency {
                    url: dep.git.clone(),
                    ref_str: Some(ref_str.to_string()),
                    commit,
                },
            );
        } else if let Some(existing) = existing_dep {
            new_deps.insert(name.clone(), existing.clone());
        }
    }

    let updated_lock = LockData {
        dependencies: new_deps,
    };

    save_lock(&lock_path, &updated_lock)?;
    Ok(updated_lock)
}
