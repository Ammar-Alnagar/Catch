import catch.cli as cli

def test_generator_golden(tmp_path):
    project_dir = tmp_path / "myproj"
    project_dir.mkdir()
    (project_dir / "src").mkdir()
    (project_dir / "src" / "main.cpp").write_text("int main(){}\n")

    toml_content = """[package]
name = "myproj"
version = "0.1.0"
type = "bin"

[build]
std = "20"
flags = ["-Wall"]
defines = ["FOO=1"]
release_flags = ["-O3"]
languages = ["CXX"]
"""
    (project_dir / "catch.toml").write_text(toml_content)
    cfg = parse_config(project_dir / "catch.toml")
    cmake_out = generate_cmakelists(cfg, project_dir)

    assert "# Generated by catch. Do not edit." in cmake_out
    assert "cmake_minimum_required(VERSION 3.24)" in cmake_out
    assert "project(myproj LANGUAGES CXX)" in cmake_out
    assert "set(CMAKE_CXX_STANDARD 20)" in cmake_out
    assert "add_compile_options(-Wall)" in cmake_out
    assert "add_compile_definitions(FOO=1)" in cmake_out
    assert 'string(APPEND CMAKE_CXX_FLAGS_RELEASE " -O3")' in cmake_out
    assert "add_executable(myproj)" in cmake_out
    assert "src/main.cpp" in cmake_out

def test_cli_new_build_run_clean(tmp_path, monkeypatch):
    monkeypatch.chdir(tmp_path)

    # catch new demo
    class ArgsNew:
        name = "demo"
        cuda = False
        mlir = False
        force = True

    cli.cmd_new(ArgsNew())

    demo_dir = tmp_path / "demo"
    assert (demo_dir / "catch.toml").exists()
    assert (demo_dir / "src" / "main.cpp").exists()
    assert (demo_dir / ".gitignore").exists()

    monkeypatch.chdir(demo_dir)

    # test generator
    cfg = cli.ensure_cmakelists(demo_dir)
    assert (demo_dir / "CMakeLists.txt").exists()

    # catch build
    class ArgsBuild:
        release = False
        verbose = False

    cli.cmd_build(ArgsBuild())
    assert (demo_dir / "build").exists()

    # catch run
    class ArgsRun:
        release = False
        verbose = False
        args = []

    cli.cmd_run(ArgsRun())

    # catch clean
    class ArgsClean:
        pass

    cli.cmd_clean(ArgsClean())
    assert not (demo_dir / "build").exists()
