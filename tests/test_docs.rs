use catch::docs::generate_docs;
use std::fs;
use tempfile::TempDir;

#[test]
fn test_generate_docs_comprehensive() {
    let tmp = TempDir::new().unwrap();
    let proj_dir = tmp.path();

    // 1. catch.toml
    let toml = r#"
[package]
name = "math_engine"
version = "2.1.0"
type = "bin"

[build]
std = "20"
flags = ["-Wall"]
defines = ["USE_FAST_MATH=1"]
languages = ["CXX"]

[dependencies]
fmt = { git = "https://github.com/fmtlib/fmt.git", tag = "10.1.1", target = "fmt::fmt" }
"#;
    fs::write(proj_dir.join("catch.toml"), toml).unwrap();

    // 2. catch.lock
    let lock = r#"# Generated by catch.
[dependencies.fmt]
url = "https://github.com/fmtlib/fmt.git"
commit = "e69e6234e402b1f1c1d3542fbc6322ec4e600f92"
"#;
    fs::write(proj_dir.join("catch.lock"), lock).unwrap();

    // 3. src/main.cpp with functions, classes, and docstrings
    let src_dir = proj_dir.join("src");
    fs::create_dir_all(&src_dir).unwrap();
    let main_cpp = r#"
#include <iostream>

/// Point representation in 2D space.
struct Point {
    double x;
    double y;
};

/**
 * Calculator class providing arithmetic operations.
 */
class Calculator {
public:
    double add(double a, double b) {
        return a + b;
    }
};

/// Entry point of the math engine.
int main(int argc, char* argv[]) {
    Calculator calc;
    std::cout << calc.add(2.0, 3.0) << std::endl;
    return 0;
}
"#;
    fs::write(src_dir.join("main.cpp"), main_cpp).unwrap();

    // 4. include/math_engine.hpp
    let inc_dir = proj_dir.join("include");
    fs::create_dir_all(&inc_dir).unwrap();
    let header_hpp = r#"
#pragma once

/// Global constant for PI
constexpr double PI = 3.1415926535;

/// Compute circumference given radius
double compute_circumference(double radius);
"#;
    fs::write(inc_dir.join("math_engine.hpp"), header_hpp).unwrap();

    // 5. Mock fetched dependency in build/_deps/fmt-src
    let dep_src = proj_dir.join("build").join("_deps").join("fmt-src");
    fs::create_dir_all(dep_src.join("include")).unwrap();
    fs::write(dep_src.join("LICENSE.rst"), "Copyright (c) 2012 - present, Victor Zverovich\n").unwrap();
    fs::write(dep_src.join("README.md"), "A modern formatting library\n").unwrap();
    fs::write(dep_src.join("include").join("fmt.h"), "// fmt header\n").unwrap();

    // 6. Mock built binary artifact
    fs::write(proj_dir.join("build").join("math_engine"), "fake binary content").unwrap();

    // Generate documentation
    let doc = generate_docs(proj_dir).unwrap();

    // Verifications:
    // Project metadata & metrics
    assert!(doc.contains("# Project: math_engine"));
    assert!(doc.contains("**Version**: `2.1.0`"));
    assert!(doc.contains("## Project Details & Code Metrics"));
    assert!(doc.contains("**Total Source Files**: 2 files"));
    assert!(doc.contains("**Built Artifact**: `build/math_engine`"));

    // Pulled library metadata
    assert!(doc.contains("## Dependencies & Pulled Libraries"));
    assert!(doc.contains("### Library: `fmt`"));
    assert!(doc.contains("**Fetch Status**: `Fetched & Cached`"));
    assert!(doc.contains("**Detected License**: `Copyright (c) 2012 - present, Victor Zverovich`"));
    assert!(doc.contains("**Description**: A modern formatting library"));
    assert!(doc.contains("**Headers Found**: 1 header files"));

    // Code Analysis & Extracted Symbols
    assert!(doc.contains("## Source Code Analysis & API Overview"));
    assert!(doc.contains("### Extracted Functions & Symbols"));
    assert!(doc.contains("- **Struct** `Point`: `struct Point`"));
    assert!(doc.contains("*Doc*: Point representation in 2D space."));
    assert!(doc.contains("- **Class** `Calculator`: `class Calculator`"));
    assert!(doc.contains("- **Function** `main`: `int main(int argc, char* argv[])`"));
    assert!(doc.contains("*Doc*: Entry point of the math engine."));
    assert!(doc.contains("- **Function** `compute_circumference`: `double compute_circumference(double radius)`"));
    assert!(doc.contains("*Doc*: Compute circumference given radius"));
}
