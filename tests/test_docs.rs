use catch::docs::generate_docs;
use std::fs;
use tempfile::TempDir;

#[test]
fn test_generate_docs_comprehensive() {
    let tmp = TempDir::new().unwrap();
    let proj_dir = tmp.path();

    // 1. catch.toml
    let toml = r#"
[package]
name = "math_engine"
version = "2.1.0"
type = "bin"

[build]
std = "20"
flags = ["-Wall"]
defines = ["USE_FAST_MATH=1"]
languages = ["CXX"]

[dependencies]
fmt = { git = "https://github.com/fmtlib/fmt.git", tag = "10.1.1", target = "fmt::fmt" }
"#;
    fs::write(proj_dir.join("catch.toml"), toml).unwrap();

    // 2. catch.lock
    let lock = r#"# Generated by catch.
[dependencies.fmt]
url = "https://github.com/fmtlib/fmt.git"
commit = "e69e6234e402b1f1c1d3542fbc6322ec4e600f92"
"#;
    fs::write(proj_dir.join("catch.lock"), lock).unwrap();

    // 3. src/main.cpp with functions, classes, and docstrings
    let src_dir = proj_dir.join("src");
    fs::create_dir_all(&src_dir).unwrap();
    let main_cpp = r#"
#include <iostream>

/// Point representation in 2D space.
struct Point {
    double x;
    double y;
};

/**
 * Calculator class providing arithmetic operations.
 */
class Calculator {
public:
    double add(double a, double b) {
        return a + b;
    }
};

/// Entry point of the math engine.
int main(int argc, char* argv[]) {
    Calculator calc;
    std::cout << calc.add(2.0, 3.0) << std::endl;
    return 0;
}
"#;
    fs::write(src_dir.join("main.cpp"), main_cpp).unwrap();

    // 4. include/math_engine.hpp
    let inc_dir = proj_dir.join("include");
    fs::create_dir_all(&inc_dir).unwrap();
    let header_hpp = r#"
#pragma once

/// Global constant for PI
constexpr double PI = 3.1415926535;

/// Compute circumference given radius
double compute_circumference(double radius);
"#;
    fs::write(inc_dir.join("math_engine.hpp"), header_hpp).unwrap();

    // 5. Mock fetched dependency in build/_deps/fmt-src
    let dep_src = proj_dir.join("build").join("_deps").join("fmt-src");
    fs::create_dir_all(dep_src.join("include")).unwrap();
    fs::write(dep_src.join("LICENSE.rst"), "Copyright (c) 2012 - present, Victor Zverovich\n").unwrap();
    fs::write(dep_src.join("README.md"), "A modern formatting library\n").unwrap();
    fs::write(dep_src.join("include").join("fmt.h"), "// fmt header\n").unwrap();

    // 6. Mock built binary artifact
    fs::write(proj_dir.join("build").join("math_engine"), "fake binary content").unwrap();

    // Generate documentation
    let doc = generate_docs(proj_dir).unwrap();

    // Verifications:
    // Project metadata & metrics
    assert!(doc.contains("# Project: math_engine"));
    assert!(doc.contains("**Version**: `2.1.0`"));
    assert!(doc.contains("## Project Details & Code Metrics"));
    assert!(doc.contains("**Total Source Files**: 2 files"));
    assert!(doc.contains("**Built Artifact**: `build/math_engine`"));

    // Pulled library metadata
    assert!(doc.contains("## Dependencies & Pulled Libraries"));
    assert!(doc.contains("### Library: `fmt`"));
    assert!(doc.contains("**Fetch Status**: `Fetched & Cached`"));
    assert!(doc.contains("**Detected License**: `Copyright (c) 2012 - present, Victor Zverovich`"));
    assert!(doc.contains("**Description**: A modern formatting library"));
    assert!(doc.contains("**Headers Found**: 1 header files"));

    // Code Analysis & Extracted Symbols
    assert!(doc.contains("## Source Code Analysis & API Overview"));
    assert!(doc.contains("### Extracted Functions & Symbols"));
    assert!(doc.contains("- **Struct** `Point`"));
    assert!(doc.contains("```cpp\nstruct Point\n```"));
    assert!(doc.contains("*Doc*: Point representation in 2D space."));
    assert!(doc.contains("- **Class** `Calculator`"));
    assert!(doc.contains("```cpp\nclass Calculator\n```"));
    assert!(doc.contains("- **Function** `main`"));
    assert!(doc.contains("```cpp\nint main(int argc, char* argv[])\n```"));
    assert!(doc.contains("*Doc*: Entry point of the math engine."));
    assert!(doc.contains("- **Function** `compute_circumference`"));
    assert!(doc.contains("```cpp\ndouble compute_circumference(double radius)\n```"));
    assert!(doc.contains("*Doc*: Compute circumference given radius"));
}

#[test]
fn test_cuda_cutlass_kernel_symbol_extraction() {
    let tmp = TempDir::new().unwrap();
    let proj_dir = tmp.path();

    let toml = r#"
[package]
name = "ker"
version = "0.1.0"
type = "bin"

[build]
std = "20"
languages = ["CXX", "CUDA"]

[dependencies]
cutlass = { git = "https://github.com/NVIDIA/cutlass.git" }
"#;
    fs::write(proj_dir.join("catch.toml"), toml).unwrap();

    let src_dir = proj_dir.join("src");
    fs::create_dir_all(&src_dir).unwrap();

    let kernel_cu = r#"
#include <cute/tensor.hpp>

using namespace cute;

/// Tiled GEMM kernel using CuTe abstractions.
template <class ProblemShape, class CtaTiler,
          class TA, class AStride, class ASmemLayout, class AThreadLayout,
          class TB, class BStride, class BSmemLayout, class BThreadLayout,
          class TC, class CStride, class CSmemLayout, class CThreadLayout,
          class Alpha, class Beta>
__global__ void
__launch_bounds__(decltype(size(CThreadLayout{}))::value)
gemm_device(ProblemShape shape_MNK, CtaTiler cta_tiler,
            TA const* A, AStride dA,
            TB const* B, BStride dB,
            TC      * C, CStride dC,
            Alpha alpha, Beta beta)
{
  CUTE_STATIC_ASSERT_V(rank(shape_MNK) == Int<3>{});
  Tensor mA = make_tensor(make_gmem_ptr(A), select<0,2>(shape_MNK), dA);
  auto cta_coord = make_coord(blockIdx.x, blockIdx.y, _);
  copy(tAgA(_,_,k_tile), tAsA);
  __syncthreads();
  gemm(tCsA, tCsB, tCrC);
}

/// Host launcher for NT GEMM
template <class TA, class TB, class TC, class Alpha, class Beta>
void gemm_nt(int m, int n, int k, Alpha alpha, TA const* A, int ldA, TB const* B, int ldB, Beta beta, TC* C, int ldC, cudaStream_t stream)
{
    // body
}

int main(int argc, char** argv)
{
    printf("done\n");
    return 0;
}
"#;
    fs::write(src_dir.join("kernel.cu"), kernel_cu).unwrap();

    // Mock cutlass in build/_deps/cutlass-src
    let cutlass_dir = proj_dir.join("build").join("_deps").join("cutlass-src");
    fs::create_dir_all(&cutlass_dir).unwrap();
    let cutlass_cmake = r#"
set(CUTLASS_VERSION_MAJOR 3)
set(CUTLASS_VERSION_MINOR 5)
set(CUTLASS_VERSION_PATCH 0)
project(CUTLASS VERSION ${CUTLASS_VERSION_MAJOR}.${CUTLASS_VERSION_MINOR}.${CUTLASS_VERSION_PATCH} LANGUAGES CXX)
"#;
    fs::write(cutlass_dir.join("CMakeLists.txt"), cutlass_cmake).unwrap();
    let cutlass_readme = r#"
# CUTLASS

![ALT](./media/images/gemm-hierarchy-with-epilogue-no-labels.png "Complete CUDA GEMM decomposition")

CUTLASS is a collection of CUDA C++ template abstractions for implementing high-performance matrix-multiplication (GEMM).
"#;
    fs::write(cutlass_dir.join("README.md"), cutlass_readme).unwrap();

    let doc = generate_docs(proj_dir).unwrap();

    // 1. Dependency checks
    assert!(doc.contains("**Library Version**: `3.5.0`"));
    assert!(!doc.contains("CUTLASS_VERSION_MAJOR"));
    assert!(doc.contains("**Description**: CUTLASS is a collection of CUDA C++ template abstractions"));
    assert!(!doc.contains("![ALT]"));

    // 2. Extracted symbol checks
    assert!(doc.contains("- **Function** `gemm_device`"));
    assert!(doc.contains("*Doc*: Tiled GEMM kernel using CuTe abstractions."));
    assert!(doc.contains("- **Function** `gemm_nt`"));
    assert!(doc.contains("*Doc*: Host launcher for NT GEMM"));
    assert!(doc.contains("- **Function** `main`"));

    // False classes from template parameters MUST NOT be present
    assert!(!doc.contains("- **Class** `ProblemShape`"));
    assert!(!doc.contains("- **Class** `CtaTiler`"));
    assert!(!doc.contains("- **Class** `TA`"));
    assert!(!doc.contains("- **Class** `Alpha`"));

    // False functions from calls inside kernel body MUST NOT be present
    assert!(!doc.contains("- **Function** `make_tensor`"));
    assert!(!doc.contains("- **Function** `make_coord`"));
    assert!(!doc.contains("- **Function** `__syncthreads`"));
    assert!(!doc.contains("- **Function** `CUTE_STATIC_ASSERT_V`"));
    assert!(!doc.contains("- **Function** `printf`"));
}
