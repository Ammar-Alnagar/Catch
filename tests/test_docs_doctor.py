import pytest
from pathlib import Path
import catch.cli as cli
import catch.docs as docs

def test_catch_docs(tmp_path, monkeypatch, capsys):
    monkeypatch.chdir(tmp_path)

    class ArgsNew:
        name = "docsproj"
        cuda = False
        mlir = False
        force = True

    cli.cmd_new(ArgsNew())
    proj_dir = tmp_path / "docsproj"
    monkeypatch.chdir(proj_dir)

    # Run catch docs
    class ArgsDocsFile:
        stdout = False

    cli.cmd_docs(ArgsDocsFile())
    doc_file = proj_dir / "docs" / "PROJECT.md"
    assert doc_file.exists()
    content = doc_file.read_text(encoding="utf-8")
    assert "<!-- Generated by catch docs. Do not edit directly. -->" in content
    assert "# Project: docsproj" in content
    assert "## Build Commands" in content

    # Run catch docs --stdout
    class ArgsDocsStdout:
        stdout = True

    cli.cmd_docs(ArgsDocsStdout())
    captured = capsys.readouterr()
    assert "# Project: docsproj" in captured.out


def test_catch_doctor(tmp_path, monkeypatch, capsys):
    monkeypatch.chdir(tmp_path)

    class ArgsDoctor:
        pass

    cli.cmd_doctor(ArgsDoctor())
    captured = capsys.readouterr()
    assert "Running catch doctor diagnostic check..." in captured.out
    assert "cmake" in captured.out
    assert "git" in captured.out
