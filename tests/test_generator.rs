use tempfile::TempDir;
use catch::config::parse_config;
use catch::generator::generate_cmakelists;

#[test]
fn test_generator_golden() {
    let tmp_dir = TempDir::new().unwrap();
    let project_dir = tmp_dir.path().join("myproj");
    std::fs::create_dir_all(&project_dir).unwrap();
    let src_dir = project_dir.join("src");
    std::fs::create_dir_all(&src_dir).unwrap();
    std::fs::write(src_dir.join("main.cpp"), "int main(){}\n").unwrap();

    let toml_content = r#"[package]
name = "myproj"
version = "0.1.0"
type = "bin"

[build]
std = "20"
flags = ["-Wall"]
defines = ["FOO=1"]
release_flags = ["-O3"]
languages = ["CXX"]
"#;
    std::fs::write(project_dir.join("catch.toml"), toml_content).unwrap();

    let cfg = parse_config(&project_dir.join("catch.toml")).unwrap();
    let cmake_out = generate_cmakelists(&cfg, &project_dir, None);

    assert!(cmake_out.contains("# Generated by catch. Do not edit."));
    assert!(cmake_out.contains("cmake_minimum_required(VERSION 3.24)"));
    assert!(cmake_out.contains("project(myproj LANGUAGES CXX)"));
    assert!(cmake_out.contains("set(CMAKE_CXX_STANDARD 20)"));
    assert!(cmake_out.contains("add_compile_options(-Wall)"));
    assert!(cmake_out.contains("add_compile_definitions(FOO=1)"));
    assert!(cmake_out.contains("string(APPEND CMAKE_CXX_FLAGS_RELEASE \" -O3\")"));
    assert!(cmake_out.contains("add_executable(myproj)"));
    assert!(cmake_out.contains("src/main.cpp"));
}
